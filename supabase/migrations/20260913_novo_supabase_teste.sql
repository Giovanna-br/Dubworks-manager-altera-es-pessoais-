create or replace function public.dw_snapshot_semana_elenco()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  select
    coalesce(e.personagem, ''),
    coalesce(e.dublador, ''),
    coalesce(e.telefone_dublador, ''),
    coalesce(e.funcao, '')
  into
    new.personagem_snapshot,
    new.dublador_snapshot,
    new.telefone_snapshot,
    new.funcao_snapshot
  from public.elenco e
  where e.id = new.elenco_id;
  return new;
end;
$$;

drop trigger if exists trg_dw_snapshot_semana_elenco on public.projeto_semana_elenco;
create trigger trg_dw_snapshot_semana_elenco
before insert on public.projeto_semana_elenco
for each row execute function public.dw_snapshot_semana_elenco();

