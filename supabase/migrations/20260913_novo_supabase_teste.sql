-- ---------- FILA WHATSAPP ----------
create table if not exists public.whatsapp_fila (
  id uuid primary key default gen_random_uuid(),
  projeto_id bigint references public.projetos(id) on delete cascade,
  semana integer not null,
  personagem text not null default '',
  dublador text not null default '',
  telefone text not null,
  mensagem text not null,
  tipo_lembrete text not null default 'manual',
  status text not null default 'na_fila',
  erro text,
  criado_em timestamptz not null default now(),
  atualizado_em timestamptz not null default now()
);

create or replace function public.enfileirar_lembrete_whatsapp(
  p_projeto_id bigint,
  p_semana integer,
  p_personagem text,
  p_dublador text,
  p_telefone text,
  p_mensagem text,
  p_tipo_lembrete text default 'manual'
)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_existente uuid;
  v_id uuid;
begin
  select id into v_existente
  from public.whatsapp_fila
  where projeto_id = p_projeto_id
    and semana = p_semana
    and regexp_replace(telefone, '\\D', '', 'g') = regexp_replace(coalesce(p_telefone,''), '\\D', '', 'g')
    and criado_em::date = now()::date
    and status <> 'erro'
  order by criado_em desc
  limit 1;

  if v_existente is not null then
    return jsonb_build_object(
      'ok', true,
      'duplicado', true,
      'id', v_existente,
      'telefone', p_telefone,
      'mensagem', 'Já existe lembrete para este número hoje.'
    );
  end if;

  insert into public.whatsapp_fila(
    projeto_id, semana, personagem, dublador, telefone, mensagem, tipo_lembrete
  ) values (
    p_projeto_id, p_semana, coalesce(p_personagem,''), coalesce(p_dublador,''),
    coalesce(p_telefone,''), coalesce(p_mensagem,''), coalesce(p_tipo_lembrete,'manual')
  ) returning id into v_id;

  return jsonb_build_object(
    'ok', true,
    'duplicado', false,
    'id', v_id,
    'telefone', p_telefone,
    'mensagem', 'Lembrete colocado na fila.'
  );
end;
$$;

grant execute on function public.enfileirar_lembrete_whatsapp(bigint, integer, text, text, text, text, text) to authenticated;

